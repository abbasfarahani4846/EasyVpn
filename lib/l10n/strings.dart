/// Minimal hand-rolled localization (en + fa). Keys live in [_en] and [_fa];
/// a missing Persian key falls back to English so the UI never shows blanks.
class S {
  S(this.locale);
  final Locale locale;

  static const supported = [Locale('en'), Locale('fa')];
  static const delegate = _SDelegate();

  static S of(BuildContext context) =>
      Localizations.of<S>(context, S) ?? S(const Locale('en'));

  bool get isFa => locale.languageCode == 'fa';

  String t(String key, [Map<String, Object?> args = const {}]) {
    var s =
        (isFa ? (_fa[key] ?? faV2[key]) : null) ?? _en[key] ?? enV2[key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }
}

extension SContext on BuildContext {
  S get s => S.of(this);
}

class _SDelegate extends LocalizationsDelegate<S> {
  const _SDelegate();
  @override
  bool isSupported(Locale l) =>
      l.languageCode == 'en' || l.languageCode == 'fa';
  @override
  Future<S> load(Locale l) async => S(l);
  @override
  bool shouldReload(_SDelegate old) => false;
}

